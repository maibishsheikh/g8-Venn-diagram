const outputDir = path.resolve('public/assets/audio');
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

function sanitize(text) {
  return text.toLowerCase().replace(/[^a-z0-9]/g, '_').substring(0, 40);
}

const mapEntries = {};

async function run() {
  console.log(`Starting generation of ${phrases.length} phrases...`);
  for (let i = 0; i < phrases.length; i++) {
    const { text, style } = phrases[i];
    const filename = `audio_${sanitize(text)}_${i}.mp3`;
    const filePath = path.join(outputDir, filename);

    if (fs.existsSync(filePath)) {
      mapEntries[text] = `/assets/audio/${filename}`;
      console.log(`[${i+1}/${phrases.length}] Cached: ${filename}`);
      continue;
    }

    try {
      const response = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}`, {
        method: 'POST',
        headers: {
          'xi-api-key': apiKey,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          text,
          model_id: VOICE_MODEL,
          voice_settings: VOICE_SETTINGS[style] || VOICE_SETTINGS.statement,
        }),
      });

      if (!response.ok) {
        console.error(`Error generating "${text}": ${response.statusText}`);
        continue;
      }

      const buffer = await response.arrayBuffer();
      fs.writeFileSync(filePath, Buffer.from(buffer));
      mapEntries[text] = `/assets/audio/${filename}`;
      console.log(`[${i+1}/${phrases.length}] Generated: ${filename}`);
      await new Promise(r => setTimeout(r, 200));
    } catch (err) {
      console.error(`Failed on phrase "${text}":`, err.message);
    }
  }

  const mapContent = `// Auto-generated by generate_audio.js\n// Static asset mapping for offline generated narration phrases in VennQuest\n\nexport const audioMap = ${JSON.stringify(mapEntries, null, 2)};\nexport default audioMap;\n`;
  fs.writeFileSync(path.resolve('src/utils/audioMap.js'), mapContent);
  console.log('Finished! Updated src/utils/audioMap.js.');
}

run();

